#!/usr/bin/env python3
"""Nav placement for the Pokémon packs: Bottom (the pack's own ring bar), Left, Right or Split (side docks).

The Pokémon packs have a ring bar (< PREV | TITLE | NEXT >) at the foot of every page. This adds side docks with one button per ring page
and a "BUTTONS" row in the pack's settings window (next to WIDE VIEW) that cycles Bottom > Left > Right > Split. With a dock the ring bars
are hidden (visibleIf $posBottom). The docks take their colours and fonts from the pack's own `.bar-btn` / `.bar-label` rules.

  python3 -I skill/tools/navkit_pokemon.py PACK_DIR [PACK_DIR ...]

Works on the FireRed / LeafGreen / Unbound layout and on the Emerald / Ruby / Sapphire / Light Platinum layout (the ring pages are found by
following the bar buttons). Safe to run again. The packs' layout.json is generated by art/layout.mjs / ui.py: run this after a rebuild.
"""
import json, os, re, sys

LUA_BEGIN, LUA_END = "-- >>> nav placement", "-- <<< nav placement"
CSS_BEGIN, CSS_END = "/* >>> nav placement */", "/* <<< nav placement */"


def box(cls, children=None, **kw):
    d = {"type": "box", "class": cls, "children": children or []}; d.update(kw); return d
def text(cls, t, **kw):
    d = {"type": "text", "class": cls, "text": t}; d.update(kw); return d
def btn(cls, children, on, **kw):
    d = {"type": "button", "class": cls, "onClick": on, "children": children}; d.update(kw); return d


def walk(n, fn):
    if isinstance(n, dict):
        fn(n)
        for c in n.get("children", []): walk(c, fn)
        if "child" in n: walk(n["child"], fn)
        if "template" in n: walk(n["template"], fn)
        for p in n.get("pages", []): walk(p["child"], fn)


def navigate_target(b):
    oc = b.get("onClick")
    for a in (oc if isinstance(oc, list) else [oc]):
        if isinstance(a, dict) and "navigate" in a: return a["navigate"]
    return None


def ring_of(stage):
    """[(page name, label)] in ring order: a ring page has a bar with a prev and a next navigate button and a title."""
    info = {}
    for p in stage["pages"]:
        found = []
        def f(n):
            if n.get("type") == "box" and n.get("class") == "bar":
                kids = n.get("children", [])
                l = [k for k in kids if k.get("type") == "button" and "bar-l" in k.get("class", "")]
                r = [k for k in kids if k.get("type") == "button" and "bar-r" in k.get("class", "")]
                m = [k for k in kids if k.get("class") == "bar-mid"]
                if l and r and m and navigate_target(l[0]) and navigate_target(r[0]):
                    title = m[0]["children"][0]["text"]
                    if "{" in title: title = ""                 # a bound title (the map's route name) is no button label
                    found.append((navigate_target(r[0]), title, n))
        walk(p["child"], f)
        if found: info[p["name"]] = found[0]
    if not info: raise SystemExit("no ring pages found")
    start = "map" if "map" in info else next(iter(info))
    order, cur = [], start
    while cur in info and cur not in [o[0] for o in order]:
        order.append((cur, info[cur][1] or cur.upper())); cur = info[cur][0]
    for name in info:                                   # a page the walk missed
        if name not in [o[0] for o in order]: order.append((name, info[name][1] or name.upper()))
    bars = [v[2] for v in info.values()]
    return order, bars


def strip_nav_block(css):
    if CSS_BEGIN in css:
        return css[:css.index(CSS_BEGIN)].rstrip("\n") + "\n"
    return css


def effective(css, selector):
    """The declarations that finally style [selector] (a lone selector, or one in a comma list): every rule in document order,
    later ones winning. Returns a dict property -> value."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    out = {}
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
        sels = [x.strip() for x in m.group(1).split(",")]
        if selector not in sels: continue
        for decl in m.group(2).split(";"):
            if ":" not in decl: continue
            k, v = decl.split(":", 1)
            out[k.strip()] = v.strip()
    return out


def block(decls, drop=()):
    return " ".join("%s: %s;" % (k, v) for k, v in decls.items() if k not in drop)


def patch_layout(pack):
    path = os.path.join(pack, "layout.json")
    lay = json.load(open(path))
    shell = [c for c in lay["children"] if c.get("class") == "shell"][0]
    stage = [c for c in shell["children"] if c.get("type") == "pages"]
    if not stage:                                      # re-run: the pages sit after the left dock
        stage = [c for c in shell["children"] if c.get("type") == "pages"]
    stage = stage[0]
    order, bars = ring_of(stage)
    for b in bars: b["visibleIf"] = "$posBottom"
    n = len(order)

    def dock(side, flag):
        return box("pdock pdock-" + side, [
            btn("dock-btn", [text("dock-label", label)], [{"navigate": page}], visibleIf="$%s%d" % (side.upper(), i), classIf={"on": "$on%d" % i})
            for i, (page, label) in enumerate(order, 1)], visibleIf=flag, classIf={"narrow": "$posSplit"})

    shell["children"] = [dock("l", "$dockL"), stage, dock("r", "$dockR")]

    # the settings row, after the last opt-btn next to WIDE VIEW
    done = []
    def add_row(node):
        kids = node.get("children", [])
        nav = [k for k in kids if k.get("class", "").startswith("opt-btn") and "cycleNav" in json.dumps(k)]
        if nav:
            for k in nav: k["class"] = "opt-btn opt-nav"
            done.append(1); return
        idx = [i for i, k in enumerate(kids) if k.get("class", "").startswith("opt-btn") and "wideView" in json.dumps(k)]
        if idx and not done:
            last = max(i for i, k in enumerate(kids) if k.get("class", "").startswith("opt-btn"))
            kids.insert(last + 1, btn("opt-btn opt-nav", [text("opt-label", "NAV"), box("grow", []), text("opt-state", "{navLabel}")], {"call": "cycleNav"}))
            done.append(1)
    walk(lay, add_row)
    if not done: print("  ! no settings row found: add a cycleNav button by hand")
    json.dump(lay, open(path, "w"), indent=2); open(path, "a").write("\n")
    return order


def patch_lua(pack, order):
    p = os.path.join(pack, "main.lua")
    src = open(p).read()
    if LUA_BEGIN in src:
        src = src[:src.index(LUA_BEGIN)].rstrip("\n") + "\n"
        src = src.replace("local function navBase(ui)", "function update(ui)")
    k = src.rfind("\nfunction update(ui)")
    if k < 0: raise SystemExit("%s: no update()" % pack)
    src = src[:k] + "\nlocal function navBase(ui)" + src[k + len("\nfunction update(ui)"):]
    navs = ", ".join('{ "%s", "%s" }' % (pg, lab) for pg, lab in order)
    lua = f'''
{LUA_BEGIN}
-- where the page buttons sit: bottom (the ring bar), left, right or split (side docks). The settings row BUTTONS cycles it.
local NAV = {{ {navs} }}
local NAV_ALIAS = {{ detail = "party", ["battle-detail"] = "battle" }}
local NAV_MODES = {{ "bottom", "left", "right", "split" }}
local navMode = 1
actions = actions or {{}}
function actions.cycleNav() navMode = navMode % #NAV_MODES + 1 end
local function navState(ui)
  local pos = NAV_MODES[navMode]
  local cur = ui.page or NAV[1][1]
  cur = NAV_ALIAS[cur] or cur
  local out = {{ posBottom = (pos == "bottom"), posSplit = (pos == "split"), navLabel = string.upper(pos) }}
  local half = (#NAV + 1) // 2
  local left, right = 0, 0
  for i, n in ipairs(NAV) do
    out["on" .. i] = (n[1] == cur)
    local l = (pos == "left") or (pos == "split" and i <= half)
    local r = (pos == "right") or (pos == "split" and i > half)
    out["L" .. i], out["R" .. i] = l, r
    if l then left = left + 1 end
    if r then right = right + 1 end
  end
  out.dockL, out.dockR = left > 0, right > 0
  return out
end
local navLastGood
function update(ui)
  local ok, r = pcall(navBase, ui)
  if ok then navLastGood = r else
    if log then log("update error: " .. tostring(r)) end
    r = navLastGood
  end
  if r and r.ready then for key, v in pairs(navState(ui or {{}})) do r[key] = v end end
  return r
end
{LUA_END}
'''
    open(p, "w").write(src.rstrip("\n") + "\n" + lua)


def patch_css(pack):
    p = os.path.join(pack, "style.css")
    css = strip_nav_block(open(p).read())
    bar = effective(css, ".bar-btn")
    pressed = effective(css, ".bar-btn:pressed")
    label = effective(css, ".bar-label")
    mid = effective(css, ".bar-mid")
    title = effective(css, ".bar-title")
    opt = effective(css, ".opt-btn")
    optlabel = effective(css, ".opt-label")
    optstate = effective(css, ".opt-state")

    # what a ring bar button looks like, minus its place in the bar
    skin = {k: v for k, v in bar.items() if k.startswith("background") or k.startswith("border")}
    skin.setdefault("border-radius", "0")
    height = bar.get("height", "44px")
    pbg = pressed.get("background-color", bar.get("background-color", "#666"))
    midbg = mid.get("background-color", "#f0e8c8")
    midborder = mid.get("border", "3px solid #333")
    midcolor = re.search(r"#[0-9a-fA-F]{3,8}|var\([^)]*\)", title.get("color", "#222222"))
    midcolor = midcolor.group(0) if midcolor else "#222222"
    lab = {k: v for k, v in label.items() if k in ("font-family", "color", "text-shadow", "letter-spacing", "line-height", "white-space")}
    lab_css = block(lab)
    rim = re.search(r"#[0-9a-fA-F]{3,8}|var\([^)]*\)", bar.get("border", "")) 
    rim = rim.group(0) if rim else "#333333"
    # border-color may be overridden separately (e.g. `.bar-btn, .pg-btn { border-color: ... }`)
    if "border-color" in bar: rim = bar["border-color"]
    skin_css = block(skin)

    extra = ""
    for sel in (".set-panel", ".set-win"):                 # the settings window is a fixed height for its rows: one more row needs room
        m = re.search(r"^%s\s*\{[^}]*?\bheight\s*:\s*(\d+)px" % re.escape(sel), css, re.M)
        if m: extra += "%s { height: %dpx; }\n" % (sel, int(m.group(1)) + 40)
    out = f'''
{CSS_BEGIN}
/* the docks and the NAV setting are skinned from the ring bar's own buttons (art/../skill/tools/navkit_pokemon.py reads .bar-btn, .bar-label, .bar-mid, .bar-title) */
.shell {{ flex-direction: row; }}
pages {{ min-width: 0; }}
.pdock {{ width: 92px; max-height: 318px; align-self: flex-start; flex-shrink: 0; gap: 6px; overflow: auto; }}
.pdock-l {{ margin-right: 8px; }}
.pdock-r {{ margin-left: 8px; }}
.dock-btn {{ {skin_css} width: 100%; height: {height}; flex-shrink: 0; margin: 0; padding: 0; flex-direction: row; align-items: center; justify-content: center; }}
.dock-btn:pressed {{ background-color: {pbg}; }}
.dock-btn.on {{ background-color: {midbg}; border: {midborder}; background-image: none; }}
.dock-label {{ {lab_css} font-size: 19px; white-space: nowrap; }}
.dock-btn.on .dock-label {{ color: {midcolor}; text-shadow: none; }}
.pdock.narrow {{ width: 76px; }}
.pdock.narrow .dock-label {{ font-size: 15px; letter-spacing: 0; }}
.opt-btn.opt-nav {{ {skin_css} }}
.opt-btn.opt-nav:pressed {{ background-color: {pbg}; }}
.opt-btn.opt-nav .opt-label {{ {lab_css} }}
.opt-btn.opt-nav .opt-state {{ color: {midcolor}; background-color: {midbg}; border: 2px solid {rim}; border-radius: 0; text-shadow: none; padding: 0 8px; }}
{extra}
{CSS_END}
'''
    open(p, "w").write(css.rstrip("\n") + "\n" + out)


def main():
    if len(sys.argv) < 2: raise SystemExit(__doc__)
    for pack in sys.argv[1:]:
        order = patch_layout(pack)
        patch_lua(pack, order)
        patch_css(pack)
        print("ok", pack, [o[1] for o in order])


main()
