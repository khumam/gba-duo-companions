#!/usr/bin/env python3
"""Writes data.lua (item names/descriptions/bonuses, PSI table, EXP curve) from the player's own ROM.

  python3 art/extract.py ../ROMs/mother3.gba

Targets the English fan translation (game code A3UJ, v1.3). Text is stored as u16 = ascii - 0x20
(space = 0x40, 0xFFFF ends a string, 0xFFxx are control codes). Tables found by hand:

  item names   0x1F8C404 + 0x2C * id          (id 0 = EMPTY)
  item descr.  string pool at 0xCF9300; item id -> string (id + 71); strings split on 0xFFFF
  PSI names    0x0D2902C + 0x28 * id          (greek letter = codes 0x3B..0x3E)
  PSI struct   0x0E18DC + 0x38 * id           (+0 = PP cost)
  PSI descr.   string (2 + rank of the id among non-EMPTY PSI ids)
  EXP          0xCDABC: 99 u32 increments; threshold to leave level L = sum(inc[0..L])
"""
import re, struct, sys

rom = open(sys.argv[1] if len(sys.argv) > 1 else "../ROMs/mother3.gba", "rb").read()
GREEK = {0x3B: "α", 0x3C: "β", 0x3D: "γ", 0x3E: "Ω"}


def dec(b, keep_nl=False):
    out = ""
    for i in range(0, len(b) - 1, 2):
        v = struct.unpack_from("<H", b, i)[0]
        if v == 0xFFFF:
            break
        if v == 0xFF01:
            out += "\n" if keep_nl else " "
        elif v == 0xFFE0:
            out += "Lucas"
        elif v >= 0x100:
            continue
        elif v in GREEK and False:
            out += GREEK[v]
        elif v == 0x40:
            out += " "
        elif v in GREEK:
            out += GREEK[v]
        else:
            out += chr(v + 0x20)
    return out


def strings(a0, a1):
    i, prev, ents = a0, True, []
    while i < a1:
        v = struct.unpack_from("<H", rom, i)[0]
        if v != 0xFFFF and prev:
            j = i
            while struct.unpack_from("<H", rom, j)[0] != 0xFFFF:
                j += 2
            ents.append(rom[i:j + 2])
            i = j
            prev = True
            continue
        prev = v == 0xFFFF
        i += 2
    return ents


descs = strings(0xCF9300, 0xD0C000)


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


items = []
for iid in range(0, 261):
    name = dec(rom[0x1F8C404 + 0x2C * iid: 0x1F8C404 + 0x2C * iid + 0x2C])
    d = dec(descs[iid + 71], True) if iid + 71 < len(descs) else ""
    bon = {}
    for key, lab in (("o", "Offense"), ("df", "Defense"), ("iq", "IQ"), ("sp", "Speed"), ("pp", "PP")):
        m = re.search(lab + r" \+(\d+)", d)
        if m:
            bon[key] = int(m.group(1))
    items.append((iid, name, d, bon))

psi_names = {}
for pid in range(0, 70):
    n = dec(rom[0xD2902C + 0x28 * pid: 0xD2902C + 0x28 * pid + 0x28])
    psi_names[pid] = n
GL = " αβγΩ"
real = [p for p in range(0, 70) if psi_names[p] and "EMPTY" not in psi_names[p] and p != 0 and p != 1]
psi = []
for rank, pid in enumerate(real):
    if pid >= 70 or pid > 62:
        break
    name = psi_names[pid]
    if 2 <= pid <= 5:
        name = "PK Love " + "αβγΩ"[pid - 2]
    pp = rom[0xE18DC + 0x38 * pid]
    d = dec(descs[2 + rank], True) if 2 + rank < len(descs) else ""
    psi.append((pid, name, pp, d))

inc = struct.unpack_from("<99I", rom, 0xCDABC)
cum, s = [], 0
for v in inc:
    s += v
    cum.append(s)

out = ["-- generated by art/extract.py from the player's ROM (do not edit)", "local D = {}", "D.items = {"]
for iid, name, d, bon in items:
    b = ",".join(f"{k}={v}" for k, v in bon.items())
    out.append(f"  [{iid}]={{n={lua_str(name)},d={lua_str(d)}{',' + b if b else ''}}},")
out.append("}")
out.append("D.psi = {")
for pid, name, pp, d in psi:
    out.append(f"  {{id={pid},n={lua_str(name)},pp={pp},d={lua_str(d)}}},")
out.append("}")
out.append("D.exp = {" + ",".join(str(c) for c in cum) + "}")
out.append("return D")
open("data.lua", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(items), "items,", len(psi), "psi")
