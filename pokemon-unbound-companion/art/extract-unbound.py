#!/usr/bin/env python3
"""Writes unbound_data.lua from the player's own Pokemon Unbound ROM (BPRE, CRC d8900587).

  python3 art/extract-unbound.py "/path/to/Pokemon Unbound.gba"

Unbound is a FireRed ROM hack (CFRU). Its data tables are repointed; the game keeps the live pointers in a table
right after the ROM header, which is where every address below comes from:

  0x144  species names      11 bytes each, index = species id (1..1293; ids 1-251 and 277-411 are the Gen 3 order,
                            Gen 4+ follow, so the national number comes from the table at 0x1A41FEC)
  0x148  move names         13 bytes each
  0x1BC  base stats         0x1C bytes each (read live by main.lua)
  0x1C0  ability names      17 bytes each
  0x1C8  items              0x2C bytes each, name first (14 bytes)
  0x1CC  battle moves       12 bytes each: effect, power, type, accuracy, pp, ...
  0x3F1CAC  map section names, one pointer each (mapsec = 0x58 + index)
"""
import struct, sys

rom = open(sys.argv[1], "rb").read()
if len(rom) != 0x2000000:
    sys.exit("not the 32 MB Unbound ROM")
u16 = lambda a: struct.unpack_from("<H", rom, a)[0]
u32 = lambda a: struct.unpack_from("<I", rom, a)[0]
ptr = lambda a: u32(a) - 0x08000000
assert rom[0xAC:0xB0] == b"BPRE"

EXTRA = {0xAD: ".", 0xAE: "-", 0xAB: "!", 0xAC: "?", 0xB4: "'", 0xB8: ",", 0xBA: "/", 0xF0: ":", 0xB5: "M", 0xB6: "F",
         0x1B: "e", 0xB1: '"', 0xB2: '"', 0xFE: " ", 0x00: " "}
def dec(b):
    out = ""
    for x in b:
        if x == 0xFF: break
        if 0xBB <= x <= 0xD4: out += chr(65 + x - 0xBB)
        elif 0xD5 <= x <= 0xEE: out += chr(97 + x - 0xD5)
        elif 0xA1 <= x <= 0xAA: out += chr(48 + x - 0xA1)
        elif x in EXTRA: out += EXTRA[x]
        else: return None
    return out.strip()

TYPES = ["normal", "fighting", "flying", "poison", "ground", "rock", "bug", "ghost", "steel", "unknown",
         "fire", "water", "grass", "electric", "psychic", "ice", "dragon", "dark"] + ["unknown"] * 5 + ["fairy"]

def lua(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["-- Generated by art/extract-unbound.py from the player's Pokemon Unbound ROM. Do not edit.", "return {"]

# species: { name, national dex }
names, dexes = ptr(0x144), 0x1A41FEC
out.append("  species = {")
n = 1
while True:
    nm = dec(rom[names + n * 11: names + n * 11 + 11])
    if rom[names + n * 11 + 10] != 0xFF or not nm: break
    out.append(f"    [{n}] = {{ name = {lua(nm)}, dex = {u16(dexes + (n - 1) * 2)} }},")
    n += 1
species_count = n - 1
out.append("  },")

# moves
mn, bm = ptr(0x148), ptr(0x1CC)
out.append("  moves = {")
moves = 0
for i in range(1, 1000):
    nm = dec(rom[mn + i * 13: mn + i * 13 + 13])
    d = rom[bm + i * 12: bm + i * 12 + 12]
    if not nm or d[:4] == b"\xff\xff\xff\xff": break
    t = TYPES[d[2]] if d[2] < len(TYPES) else "unknown"
    out.append(f"    [{i}] = {{ name = {lua(nm)}, type = \"{t}\", power = {d[1]}, acc = {d[3]}, pp = {d[4]} }},")
    moves = i
out.append("  },")

# abilities
an = ptr(0x1C0)
out.append("  abilities = {")
abil = 0
for i in range(1, 400):
    nm = dec(rom[an + i * 17: an + i * 17 + 17])
    if not nm or rom[an + i * 17 + 16] not in (0xFF, 0): break
    out.append(f"    [{i}] = {lua(nm)},")
    abil = i
out.append("  },")

# items
it = ptr(0x1C8)
out.append("  items = {")
items, misses, item_names = 0, 0, {}
for i in range(1, 1500):
    nm = dec(rom[it + i * 44: it + i * 44 + 14])
    if not nm:                       # a few ids are unused: stop after a run of them
        misses += 1
        if misses >= 4: break
        continue
    misses = 0
    out.append(f"    [{i}] = {lua(nm)},")
    item_names[i] = nm
    items = i
out.append("  },")

# map sections: mapsec = 0x58 + index
ms = 0x3F1CAC
out.append("  mapsecs = {")
i = 0
while True:
    p = u32(ms + i * 4)
    if not (0x08000000 <= p < 0x0A000000): break
    nm = dec(rom[p - 0x08000000: p - 0x08000000 + 24])
    if not nm: break
    out.append(f"    [{0x58 + i}] = {lua(nm)},")
    i += 1
out.append("  },")
# bag icons: the shipped PNGs are the FireRed ones, keyed by FireRed's item ids. An Unbound item gets the icon of the
# FireRed item with the same name (Unbound's own extra items fall back to a generic icon).
import os, re
here = __file__.rsplit("/", 2)[0]
norm = lambda n: n.replace("é", "e").replace("'", "").lower()
vanilla = {norm(m.group(2)): int(m.group(1)) for m in re.finditer(r'\[(\d+)\] = "([^"]*)"', open(here + "/art/vanilla_item_names.lua").read())}
have = {int(f[:-4]) for f in os.listdir(here + "/assets/items") if f[:-4].isdigit()}
names = item_names
out.append("  itemIcons = {")
out.append("    " + ", ".join(f"[{i}] = {vanilla[norm(n)]}" for i, n in sorted(names.items()) if norm(n) in vanilla and vanilla[norm(n)] in have))
out.append("  },")
out.append("}")
open(__file__.rsplit("/", 2)[0] + "/unbound_data.lua", "w").write("\n".join(out) + "\n")
print("species", species_count, "moves", moves, "abilities", abil, "items", items, "mapsecs", i)
