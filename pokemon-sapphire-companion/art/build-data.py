# Sapphire lookup tables that aren't readable from the ROM at runtime. Run: python3 art/build-data.py <sapphire.gba>
# Offsets are for the USA 1.0 ROM (pret/pokeruby symbols):
#   national: internal species id -> national dex number (gSpeciesToNationalPokedexNum, 0x081FC4A6)
#   tmhm: TM/HM index -> move id (found by its first three moves: Focus Punch, Dragon Claw, Water Pulse)
#   contest: move id -> {effect, category} (gContestMoves, 0x083CF5EC, 8 bytes per move)
import os, struct, sys

rom = open(sys.argv[1], "rb").read()
u16 = lambda o: struct.unpack_from("<H", rom, o)[0]
BASE = 0x08000000
NATIONAL, CONTEST = 0x081FC4A6 - BASE, 0x083CF5EC - BASE

national = {i: u16(NATIONAL + (i - 1) * 2) for i in range(1, 412)}
national = {i: (n if n <= 386 else 0) for i, n in national.items()}
tm = rom.find(struct.pack("<3H", 264, 337, 352))
tmhm = [u16(tm + i * 2) for i in range(58)]
contest = {m: (rom[CONTEST + m * 8], rom[CONTEST + m * 8 + 1]) for m in range(1, 355)}

icons = sorted(int(f[:-4]) for f in os.listdir(os.path.join(os.path.dirname(__file__), "..", "assets", "items")) if f[:-4].isdigit())
out = ["-- Sapphire game data, generated by art/build-data.py from the ROM. Do not edit by hand.", "return {", "  national = {"]
out += [f"    [{i}] = {n}," for i, n in national.items()]
out += ["  },", "  itemIcons = {" + ", ".join(f"[{i}] = true" for i in icons) + "},", "  tmhm = {" + ", ".join(str(m) for m in tmhm) + "},", "  contest = {"]
out += [f"    [{m}] = {{ {e}, {c} }}," for m, (e, c) in sorted(contest.items())]
out += ["  },", "}", ""]
open(os.path.join(os.path.dirname(__file__), "..", "game_data.lua"), "w").write("\n".join(out))
print("national", len(national), "tm@", hex(tm), "tmhm", tmhm[:4], "contest", len(contest))
