# Light Platinum lookup tables that aren't readable from the ROM at runtime. Run:
#   python3 art/build-data.py "Pokemon - Light Platinum (U).gba"
# Light Platinum is a Ruby hack that keeps Ruby's table addresses (pret/pokeruby symbols) and squeezes Gen 4/5
# Pokemon into the species list (ids 252-276 and a few replaced Hoenn slots, 411 species in all):
#   national: internal species id -> the game's own national number (gSpeciesToNationalPokedexNum, 0x081FC516);
#             the game numbers its extra Pokemon 387-411, and a replaced slot keeps the old number
#   official: internal species id -> the real national dex number, by species name (art/official_names.lua is
#             the Unbound pack's species list); the shipped sprites are keyed by this
#   tmhm: TM/HM index -> move id (found by its first three moves: Focus Punch, Dragon Claw, Water Pulse)
#   contest: move id -> {effect, category} (gContestMoves, 0x083CF594, 8 bytes per move)
import os, struct, sys

rom = open(sys.argv[1], "rb").read()
u16 = lambda o: struct.unpack_from("<H", rom, o)[0]
BASE = 0x08000000
NATIONAL, CONTEST = 0x081FC516 - BASE, 0x083CF594 - BASE

national = {i: u16(NATIONAL + (i - 1) * 2) for i in range(1, 412)}

import re
CH = {0xAD: ".", 0xAE: "-", 0xB4: "'", 0xB5: "m", 0xB6: "f", 0x00: " "}
def text(a, n):
    out = ""
    for x in rom[a:a + n]:
        if x == 0xFF: break
        out += chr(65 + x - 0xBB) if 0xBB <= x <= 0xD4 else chr(97 + x - 0xD5) if 0xD5 <= x <= 0xEE else CH.get(x, "")
    return out
here = os.path.dirname(__file__)
dexOf = {}
for m in re.finditer(r'\[(\d+)\] = \{ name = "([^"]*)", dex = (\d+) \}', open(os.path.join(here, "official_names.lua")).read()):
    dexOf.setdefault(re.sub(r"[^a-z0-9]", "", m.group(2).lower().replace("♂", "m").replace("♀", "f")), int(m.group(3)))
SPECIES_NAMES = 0x081F716C - BASE
official = {}
for i in range(1, 412):
    name = re.sub(r"[^a-z0-9]", "", text(SPECIES_NAMES + i * 11, 11).lower())
    official[i] = dexOf.get(name, 0)
    if not official[i]: print("no official number for", i, name)
tm = rom.find(struct.pack("<3H", 264, 337, 352))
tmhm = [u16(tm + i * 2) for i in range(58)]
contest = {m: (rom[CONTEST + m * 8], rom[CONTEST + m * 8 + 1]) for m in range(1, 355)}

icons = sorted(int(f[:-4]) for f in os.listdir(os.path.join(os.path.dirname(__file__), "..", "assets", "items")) if f[:-4].isdigit())
out = ["-- Ruby game data, generated by art/build-data.py from the ROM. Do not edit by hand.", "return {", "  national = {"]
out += [f"    [{i}] = {n}," for i, n in national.items()]
out += ["  },", "  official = {"]
out += [f"    [{i}] = {n}," for i, n in official.items()]
out += ["  },", "  itemIcons = {" + ", ".join(f"[{i}] = true" for i in icons) + "},", "  tmhm = {" + ", ".join(str(m) for m in tmhm) + "},", "  contest = {"]
out += [f"    [{m}] = {{ {e}, {c} }}," for m, (e, c) in sorted(contest.items())]
out += ["  },", "}", ""]
open(os.path.join(os.path.dirname(__file__), "..", "game_data.lua"), "w").write("\n".join(out))
print("national", len(national), "tm@", hex(tm), "tmhm", tmhm[:4], "contest", len(contest))
