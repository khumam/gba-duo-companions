-- journey.lua : the JOURNEY page — bosses beaten, relics (Dracula's parts), spell books and furniture found,
-- with where each one is in the castle, plus a summary of the whole run.
-- Boss death bits 0x02000358: bit n = boss n (1–18). The index is the boss door's var B in the ROM's room data
-- (the same as DSVEdit's table); killing the Cyclops set bit 16 by itself. Places: the boss room / pickup cell
-- from the ROM's room lists (art/journeydata.py), area name = the map tile's region (as in the header).
local H = pack.require("hod")
local Map = pack.require("map")
local Book = pack.require("book")
local A = H.A
local M = {}

-- generated by art/journeydata.py: {map x, map y, castle B} of each pickup and boss room
M.BOOK_AT = { [0] = {20,15,0}, {10,15,0}, {59,25,0}, {36,14,1}, {16,32,1} }
M.RELIC_AT = { [0] = {15,23,0}, {11,33,1}, {37,32,0}, {12,22,0}, {23,18,0}, {26,19,0}, {36,8,0}, {46,17,1}, {5,20,1}, {38,26,0}, {52,28,0}, {27,15,0} }
M.FURN_AT = { [0] = {31,21,0}, {54,14,1}, {30,33,0}, {39,18,1}, {45,31,1}, {55,19,0}, {24,27,1}, {40,18,1}, {11,19,1}, {4,20,1}, {16,32,1}, {12,26,1}, {25,33,1}, {15,26,0}, {15,26,0}, {32,5,1}, {37,9,1}, {19,19,1}, {46,27,1}, {52,28,1}, {59,25,0}, {28,33,0}, {24,33,1}, {20,19,1}, {31,5,0}, {45,13,0}, {44,13,0}, {47,27,1}, {36,13,0}, {44,13,1}, {28,26,0} }
M.BOSS_AT = { {20,17,0}, {12,33,1}, {16,23,0}, {48,30,1}, {34,14,1}, {45,16,0}, {46,22,0}, {55,14,0}, {52,17,1}, {45,16,1}, {35,16,1}, {34,14,0}, {12,33,0}, {48,30,0}, {38,32,0}, {16,23,1}, {1,23,0}, {29,7,0} }


-- Boss index 1–18 -> enemy id (names = enemy texts; 0x77 = the Talos that chases Juste at the start).
M.BOSS_ID = { 0x09, 0x1F, 0x11, 0x1E, 0x28, 0x2E, 0x36, 0x37, 0x42, 0x43, 0x44, 0x53, 0x54, 0x55, 0x56, 0x60, 0x77, 0x49 }
local CHASE = 17                                  -- never set in Maxim Mode (2 saves at ~98 %, chase room explored)
local META = 0x080DAD94
local UNKNOWN = 0x253                             -- "??????????"
M.TIP_BOSS = 3000                                 -- the BATTLE page's tip range: 3000 + enemy id

local function areaAt(c)
  local t = mem.u16(META + 2 * (c[2] * 64 + c[1]))
  return H.AREAS[((t >> 8) & 15) + 1]
end

local placeCache = {}
local function place(key, c)
  local p = placeCache[key]
  if not p then p = { area = areaAt(c), b = c[3] == 1 }; placeCache[key] = p end
  return p
end

local function bits(addr, n)
  local v = 0
  for k = 0, (n - 1) // 8 do v = v | (mem.u8(addr + k) << (8 * k)) end
  return v & ((1 << n) - 1)
end

local function popcount(v) local n = 0; while v ~= 0 do n = n + (v & 1); v = v >> 1 end; return n end

local VIEWS = {
  relics = { kind = "relic", at = M.RELIC_AT, addr = A.relicsOwned, n = 12, title = "RELICS" },
  books  = { kind = "book",  at = M.BOOK_AT,  addr = A.booksOwned,  n = 5,  title = "SPELL BOOKS" },
  furn   = { kind = "furn",  at = M.FURN_AT,  addr = A.furniture,   n = 31, title = "FURNITURE" },
}

local function pct(n) return string.format("%d.%d%%", n * 1000 // 674 // 10, n * 1000 // 674 % 10) end

function M.page(out, ui, chr)
  local maxim = chr == 2
  local view = ui.jv or "bosses"
  if view ~= "relics" and view ~= "books" and view ~= "furn" then view = "bosses" end
  local where = ui.wh == true or ui.wh == "true"
  local tip = tonumber(ui.tip) or -1
  local flags = mem.u32(A.bossFlags)

  -- summary
  local beaten, bossTotal = 0, maxim and 17 or 18
  for i = 1, 18 do
    if flags & (1 << i) ~= 0 and not (maxim and i == CHASE) then beaten = beaten + 1 end
  end
  local own = {}
  for key, V in pairs(VIEWS) do own[key] = maxim and 0 or bits(V.addr, V.n) end
  local vlad = popcount((own.relics >> 6) & 63)
  local function frac(a, b) return b > 0 and a / b or 0 end
  local na, nb = Map.count(0), Map.count(1)
  local kills = 0
  for i = 0, 99 do if Book.killed(i) then kills = kills + 1 end end
  local relN, bookN, furN = popcount(own.relics), popcount(own.books), popcount(own.furn)
  out.sumRows = {
    { key = "bosses", label = "BOSSES", value = beaten .. "/" .. bossTotal, f = frac(beaten, bossTotal), on = view == "bosses" },
    { key = "relics", label = "RELICS", value = maxim and "-" or (relN .. "/12"), f = frac(relN, 12), on = view == "relics" },
    { key = "books", label = "SPELL BOOKS", value = maxim and "-" or (bookN .. "/5"), f = frac(bookN, 5), on = view == "books" },
    { key = "furn", label = "FURNITURE", value = maxim and "-" or (furN .. "/31"), f = frac(furN, 31), on = view == "furn" },
  }
  out.vladText = maxim and "-" or (vlad .. "/6")
  out.mapText, out.mapF = pct(na + nb), frac(na + nb, 2 * 674)
  out.killText, out.killF = kills .. "/100", kills / 100
  out.modeText = maxim and "Maxim Mode" or "Juste Mode"

  -- the list
  local rows = {}
  if view == "bosses" then
    out.jTitle, out.jCount = "BOSSES", beaten .. "/" .. bossTotal
    for i = 1, 18 do
      local id, p = M.BOSS_ID[i], place("b" .. i, M.BOSS_AT[i])
      local done = flags & (1 << i) ~= 0
      local r = { lamp = true, noLamp = false, hasIcon = false, icon = "", missing = not done, done = done,
                  vlad = false, isA = not p.b, isB = p.b, castle = p.b and "B" or "A", tip = -1, sel = false }
      if maxim and i == CHASE then
        r.name, r.place, r.missing, r.done, r.off = H.text(H.T.enemy + id), "Juste Mode only", true, false, true
      elseif done or where then
        r.name, r.place, r.tip = H.text(H.T.enemy + id), p.area, M.TIP_BOSS + id
      else
        r.name, r.place = H.text(UNKNOWN), ""
      end
      r.showPlace = r.place ~= ""
      r.sel = r.tip >= 0 and r.tip == tip
      rows[#rows + 1] = r
    end
  else
    local V = VIEWS[view]
    out.jTitle = V.title
    out.jCount = maxim and "-" or (popcount(own[view]) .. "/" .. V.n)
    if not maxim then
      for i = 0, V.n - 1 do
        local p = place(view .. i, V.at[i])
        local has = own[view] & (1 << i) ~= 0
        local r = { lamp = false, noLamp = true, missing = not has, done = has, vlad = view == "relics" and i >= 6 and (has or where),
                    isA = not p.b, isB = p.b, castle = p.b and "B" or "A", tip = -1, sel = false, hasIcon = false, icon = "" }
        if has or where then
          r.name, r.place, r.tip = H.name(V.kind, i), p.area, H.descId(V.kind, i)
        else
          r.name, r.place = H.text(UNKNOWN), ""
        end
        if has then
          local key = H.icon(V.kind, i)
          r.icon, r.hasIcon = key or "", key ~= nil
        end
        r.qMark = not r.hasIcon
        r.showPlace = r.place ~= ""
        r.sel = r.tip >= 0 and r.tip == tip
        rows[#rows + 1] = r
      end
    end
  end
  out.jRows = rows
  out.jEmpty = #rows == 0
  out.jEmptyText = "Maxim Mode has no relics, spell books or furniture to find."
  out.jMore = #rows > 10
  out.where, out.noWhere = where, not where
end

return M
