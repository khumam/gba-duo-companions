# Emerald lookup tables that aren't readable from the ROM at runtime. Run: python3 art/build-data.py <emerald.gba>
#   - national: internal species id -> national dex number (sSpeciesToNationalPokedexNum, read from the ROM)
#   - tmhm: TM/HM index -> move id (gTMHMMoves, read from the ROM)
#   - contest: move id -> {effect, category} (pret/pokeemerald src/data/contest_moves.h)
import os, re, struct, sys, urllib.request

rom = open(sys.argv[1], "rb").read()
u16 = lambda o: struct.unpack_from("<H", rom, o)[0]
B = "https://raw.githubusercontent.com/pret/pokeemerald/master/"
get = lambda p: urllib.request.urlopen(B + p).read().decode()

NATIONAL = 0x31DC82
national = {i: u16(NATIONAL + (i - 1) * 2) for i in range(1, 412)}
national = {i: (n if n <= 386 else 0) for i, n in national.items()}

seq = struct.pack("<3H", 264, 337, 352)  # TM01 Focus Punch, TM02 Dragon Claw, TM03 Water Pulse
tm = rom.find(seq)
tmhm = [u16(tm + i * 2) for i in range(58)]

moves = {m[0]: int(m[1]) for m in re.findall(r"#define (MOVE_\w+)\s+(\d+)", get("include/constants/moves.h"))}
effects = {m[0]: int(m[1]) for m in re.findall(r"#define (CONTEST_EFFECT_\w+)\s+(\d+)", get("include/constants/contest.h"))}
cats = {"COOL": 0, "BEAUTY": 1, "CUTE": 2, "SMART": 3, "TOUGH": 4}
contest = {}
for name, body in re.findall(r"\[(MOVE_\w+)\]\s*=\s*\{(.*?)\n    \},", get("src/data/contest_moves.h"), re.S):
    e = re.search(r"\.effect = (CONTEST_EFFECT_\w+)", body)
    c = re.search(r"\.contestCategory = CONTEST_CATEGORY_(\w+)", body)
    if e and c and name in moves:
        contest[moves[name]] = (effects[e.group(1)], cats[c.group(1)])

icons = sorted(int(f[:-4]) for f in os.listdir(os.path.join(os.path.dirname(__file__), "..", "assets", "items")) if f[:-4].isdigit())
out = ["-- Emerald game data, generated by art/build-data.py. Do not edit by hand.", "return {", "  national = {"]
out += [f"    [{i}] = {n}," for i, n in national.items()]
out += ["  },", "  itemIcons = {" + ", ".join(f"[{i}] = true" for i in icons) + "},", "  tmhm = {" + ", ".join(str(m) for m in tmhm) + "},", "  contest = {"]
out += [f"    [{m}] = {{ {e}, {c} }}," for m, (e, c) in sorted(contest.items())]
out += ["  },", "}", ""]
open(os.path.join(os.path.dirname(__file__), "..", "game_data.lua"), "w").write("\n".join(out))
print("national", len(national), "tm@", hex(tm), "tmhm", tmhm[:4], "contest", len(contest))
